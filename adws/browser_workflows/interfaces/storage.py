"""Persistence, split by who needs what: a player reads, an editor writes,
the recorder stages, the run log appends."""
from __future__ import annotations

from typing import Protocol

from ..models import ( PlaybackRun, RawBrowserEvent, RecordedAction, Recording, RecordingSessionInfo,
                       RecordingStep, RecordingSummary, RepairProposal, StepResult )


class IPlaybackRepository( Protocol ):
    """Read-only: what can be played, and one playback's definition."""

    def summaries( self ) -> list[ RecordingSummary ]: ...

    def by_name( self, name: str ) -> Recording | None: ...

    def by_id( self, recording_id: int ) -> Recording | None: ...


class IRecordingRepository( IPlaybackRepository, Protocol ):
    """Saves and changes whole recordings and their steps."""

    def create( self, name: str, actions: list[ RecordedAction ], description: str = "" ) -> Recording: ...

    def rename( self, recording_id: int, name: str ) -> None: ...

    def delete( self, recording_id: int ) -> None: ...

    def replace_steps( self, recording_id: int, steps: list[ RecordedAction ]) -> Recording: ...

    def update_step( self, step: RecordingStep ) -> None: ...

    def step( self, step_id: int ) -> tuple[ int, RecordingStep ] | None:
        """A step by id, with its recording's id."""
        ...


class IRecordingSessionStore( Protocol ):
    """Sessions and their captured events, durable before anything is named."""

    def open( self, info: RecordingSessionInfo ) -> None: ...

    def update( self, info: RecordingSessionInfo ) -> None: ...

    def append( self, session_id: str, event: RawBrowserEvent ) -> int: ...

    def events( self, session_id: str ) -> list[ RawBrowserEvent ]: ...

    def get( self, session_id: str ) -> RecordingSessionInfo | None: ...

    def latest_open( self ) -> RecordingSessionInfo | None: ...


class IPlaybackRunLog( Protocol ):
    """Every run, and every step's outcome in it."""

    def start( self, recording_id: int, actor: str ) -> int: ...

    def record( self, result: StepResult ) -> None: ...

    def finish( self, run_id: int, status: str, message: str ) -> None: ...

    def run( self, run_id: int ) -> PlaybackRun | None: ...

    def recent( self, limit: int = 20, recording_id: int | None = None ) -> list[ PlaybackRun ]: ...


class ILocatorRepairStore( Protocol ):
    def propose( self, proposal: RepairProposal ) -> RepairProposal: ...

    def get( self, repair_id: int ) -> RepairProposal | None: ...

    def mark_applied( self, repair_id: int ) -> None: ...
